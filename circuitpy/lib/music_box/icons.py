def _keys(active):
    """A picture of the 3x4 keypad with the keys in play filled in."""
    rows = []
    for r in range(SIZE):
        row = ""
        for c in range(SIZE):
            key_row, y = divmod(r, 4)
            key_col, x = divmod(c - 2, 4) if 2 <= c < 14 else (None, None)
            on = key_col is not None and y < 3 and x < 3 and key_row * 3 + key_col in active
            row += "#" if on else "."
        rows.append(row)
    return "\n".join(rows)


def _parse(art):
    return [line for line in art.strip().split("\n")]


ICONS = {name: _parse(art) for name, art in _ART.items()}
ICONS["keys4"] = _parse(_keys((0, 2, 9, 11)))
ICONS["keys6"] = _parse(_keys((0, 1, 2, 9, 10, 11)))
ICONS["keys12"] = _parse(_keys(range(12)))
